const languageButtons = document.querySelectorAll('.language-button');
const menuToggle = document.querySelector('.menu-toggle');
const navigation = document.querySelector('.main-navigation');

function setLanguage(language) {
    const selected = translations[language] ? language : 'vi';
    const words = translations[selected];

    document.documentElement.lang = selected;
    document.title = words.page_title;

    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute('content', words.page_description);

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        if (Object.prototype.hasOwnProperty.call(words, key)) {
            element.innerHTML = words[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (Object.prototype.hasOwnProperty.call(words, key)) {
            element.setAttribute('placeholder', words[key]);
        }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
        const key = element.dataset.i18nAria;
        if (Object.prototype.hasOwnProperty.call(words, key)) {
            element.setAttribute('aria-label', words[key]);
        }
    });

    languageButtons.forEach((button) => {
        const active = button.dataset.language === selected;
        button.classList.toggle('is-active', active);
        button.setAttribute('aria-pressed', String(active));
    });

    localStorage.setItem('talkEnglishLanguage', selected);
}

function closeMenu() {
    if (!navigation || !menuToggle) return;
    navigation.classList.remove('is-open');
    menuToggle.setAttribute('aria-expanded', 'false');

    const language = document.documentElement.lang || 'vi';
    menuToggle.setAttribute(
        'aria-label',
        translations[language]?.menu_open || translations.vi.menu_open
    );
}

languageButtons.forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
});

if (menuToggle && navigation) {
    menuToggle.addEventListener('click', () => {
        const opening = !navigation.classList.contains('is-open');
        navigation.classList.toggle('is-open', opening);
        menuToggle.setAttribute('aria-expanded', String(opening));

        const language = document.documentElement.lang || 'vi';
        menuToggle.setAttribute(
            'aria-label',
            opening
                ? translations[language]?.menu_close
                : translations[language]?.menu_open
        );
    });

    navigation.querySelectorAll('a').forEach((link) => {
        link.addEventListener('click', closeMenu);
    });

    document.addEventListener('click', (event) => {
        if (
            navigation.classList.contains('is-open') &&
            !navigation.contains(event.target) &&
            !menuToggle.contains(event.target)
        ) {
            closeMenu();
        }
    });

    window.addEventListener('resize', () => {
        if (window.innerWidth > 1020) closeMenu();
    });
}

