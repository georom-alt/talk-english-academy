const enquiryForm = document.getElementById('enquiry-form');
const formStatus = document.getElementById('form-status');
const registrationSubmit = document.getElementById('registration-submit');
const registrationEmail = document.getElementById('registration-email');

function showFormStatus(key, state = '') {
    if (!formStatus) return;
    const language = document.documentElement.lang || 'vi';
    formStatus.textContent = translations[language]?.[key] || translations.vi[key] || '';
    formStatus.dataset.state = state;
}

function buildRegistrationMessage() {
    const language = document.documentElement.lang || 'vi';
    const formData = new FormData(enquiryForm);
    const labels = language === 'en'
        ? {
            heading: 'Talk English – Free Trial Lesson Registration',
            name: 'Name', phone: 'Phone / Zalo', email: 'Email',
            level: 'Current level', goal: 'Learning goal',
            time: 'Preferred class time', message: 'Message'
          }
        : {
            heading: 'Talk English – Đăng Ký Buổi Học Thử Miễn Phí',
            name: 'Họ và tên', phone: 'Điện thoại / Zalo', email: 'Email',
            level: 'Trình độ hiện tại', goal: 'Mục tiêu học',
            time: 'Thời gian phù hợp', message: 'Tin nhắn'
          };

    return [
        labels.heading,
        '',
        `${labels.name}: ${formData.get('name') || ''}`,
        `${labels.phone}: ${formData.get('phone_zalo') || ''}`,
        `${labels.email}: ${formData.get('email') || (language === 'en' ? 'Not provided' : 'Không cung cấp')}`,
        `${labels.level}: ${formData.get('current_level') || ''}`,
        `${labels.goal}: ${formData.get('learning_goal') || ''}`,
        `${labels.time}: ${formData.get('preferred_time') || ''}`,
        `${labels.message}: ${formData.get('message') || (language === 'en' ? 'None' : 'Không có')}`
    ].join('\n');
}

if (enquiryForm) {
    enquiryForm.addEventListener('submit', async (event) => {
        event.preventDefault();

        if (!enquiryForm.reportValidity()) return;

        const honeypot = enquiryForm.querySelector('[name="_honey"]');
        if (honeypot?.value) return;

        const language = document.documentElement.lang || 'vi';
        const originalButtonText = registrationSubmit?.textContent || '';
        const registrationText = buildRegistrationMessage();

        showFormStatus('form_sending', 'sending');
        if (registrationSubmit) {
            registrationSubmit.disabled = true;
            registrationSubmit.textContent = translations[language]?.form_sending || 'Preparing...';
        }

        try {
            await navigator.clipboard.writeText(registrationText);
            showFormStatus('form_success', 'success');
            document.querySelector('.admin-card')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
        } catch (error) {
            console.error('Clipboard error:', error);
            const fallback = document.createElement('textarea');
            fallback.value = registrationText;
            fallback.setAttribute('readonly', '');
            fallback.style.position = 'fixed';
            fallback.style.opacity = '0';
            document.body.appendChild(fallback);
            fallback.select();
            const copied = document.execCommand('copy');
            fallback.remove();
            showFormStatus(copied ? 'form_success' : 'form_error', copied ? 'success' : 'error');
            if (copied) document.querySelector('.admin-card')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
        } finally {
            if (registrationSubmit) {
                registrationSubmit.disabled = false;
                registrationSubmit.textContent = originalButtonText || translations[language]?.form_submit;
            }
        }
    });

    registrationEmail?.addEventListener('click', () => {
        if (!enquiryForm.reportValidity()) return;

        const language = document.documentElement.lang || 'vi';
        const subject = language === 'en'
            ? 'Free Trial Lesson Registration'
            : 'Đăng Ký Buổi Học Thử Miễn Phí';
        const mailto = `mailto:hello@noiladuoc.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(buildRegistrationMessage())}`;
        window.location.href = mailto;
    });
}


// Accessible profile modals for Teacher George and An.
let lastProfileTrigger = null;
function closeProfileModal(modal) {
    if (!modal) return;
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    lastProfileTrigger?.focus();
}

document.querySelectorAll('[data-profile-open]').forEach((trigger) => {
    trigger.addEventListener('click', () => {
        const modal = document.getElementById(trigger.dataset.profileOpen);
        if (!modal) return;
        lastProfileTrigger = trigger;
        modal.classList.add('is-open');
        modal.setAttribute('aria-hidden', 'false');
        document.body.classList.add('modal-open');
        modal.querySelector('.profile-modal-close')?.focus();
    });
});

document.querySelectorAll('.profile-modal').forEach((modal) => {
    modal.querySelectorAll('[data-profile-close]').forEach((control) => {
        control.addEventListener('click', () => closeProfileModal(modal));
    });
});

document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeProfileModal(document.querySelector('.profile-modal.is-open'));
});

// v1.3: highlight the visible page section in the desktop navigation.
const observedSections = [...document.querySelectorAll('main section[id]')];
const navigationLinks = [...document.querySelectorAll('.main-navigation a[href^="#"]')];
if ('IntersectionObserver' in window && observedSections.length) {
    const sectionObserver = new IntersectionObserver((entries) => {
        const visible = entries
            .filter((entry) => entry.isIntersecting)
            .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
        if (!visible) return;
        navigationLinks.forEach((link) => {
            const active = link.getAttribute('href') === `#${visible.target.id}`;
            link.classList.toggle('is-current', active);
            if (active) link.setAttribute('aria-current', 'location');
            else link.removeAttribute('aria-current');
        });
    }, { rootMargin: '-30% 0px -60% 0px', threshold: [0.05, 0.3, 0.6] });
    observedSections.forEach((section) => sectionObserver.observe(section));
}
